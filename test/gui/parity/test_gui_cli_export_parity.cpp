struct ParityScene {
  const char* name;
  // Renderer fields, applied on top of the loaded document.
  int lens_type;
  float fov;
  float azimuth;
  float elevation;
  float roll;
  int visible;
  float background_srgb[3];
  // Which tone-reproduction operator turns radiance into pixels, and the ground it lays it on.
  // `tone` mirrors config::RenderConfig::Tone and GuiState::RenderConfig::tone (0 screen, 1 print);
  // `paper_srgb` is read only under print, and `background_srgb` only under screen. Both are filled
  // on every scene regardless, so a row's diff against its neighbours is the tone fields and
  // nothing else.
  int tone;
  float paper_srgb[3];
  // Display-group framing.
  gui::AspectPreset aspect_preset;
  bool aspect_portrait;
  // The celestial horizon. ON in both scenes since the preview stopped deriving it in its own
  // fragment shader — it belongs to the "two readings of one curve" family now, like the three
  // below. It is still the odd member of that family in one respect: its opacity cannot be raised
  // to 1 the way the grid's and the markers' are, because core paints it from a fixed constant.
  // See the header note where its exclusion used to be.
  bool show_horizon;
  // Angular-distance circles. ON in both scenes, unlike the horizon, because these two arms are
  // not two implementations of the same curve — they are two readings of one. See the exclusion
  // note above for why that makes turning them on raise the PSNR rather than lower it.
  bool show_sun_circles;
  // The coordinate grid, on in both scenes for the same reason the circles are: both arms
  // evaluate the same level-set definition, so it is one curve twice rather than two
  // implementations. See the exclusion note above.
  bool show_grid;
  // The sky reference-point ring markers, on in both scenes and the one family that IS two
  // readings of one call: both arms take the points from core's anchor walk
  // (LUMICE_ComputeAnnotationAnchors on the GUI side) and draw a ring of the config's radius
  // around each. Unlike the three line families this one is
  // a SET of six independent members, each with its own colour — which is what the encoding
  // assertion below reads, since the pixels cannot (see the markers row in the field table).
  //
  // ALL SIX rather than a representative subset: four of them (sun, subsun, anthelion, antisolar)
  // are defined RELATIVE TO THE SUN, so they are the only rows in this table whose position depends
  // on a field of the document other than the view — and the export has to carry that field for the
  // child process to place them where the preview did. A subset that left them out would leave the
  // whole sun-relative half of the id space unexercised end to end.
  bool show_markers;
  // The document's manual EV offset (GuiState::RenderConfig::exposure_offset), written as-is. It
  // is the ONE knob both arms read: the export bakes 2^offset into the CLI's intensity_factor
  // (file_io.cpp BuildScene, kJsonExport) and the preview shader multiplies by 2^(offset+ev_auto)
  // (mono_exposure_scale.hpp; only ev_auto is clamped). 0 (the field's own default, byte-unchanged)
  // for the simulation scenes; -8 for the lines-only scenes — the GUI's own EV slider clamps this
  // field to [-8, 16] every frame it is drawn (src/gui/field_editor_registry.cpp:570
  // FixedDomain), so -8 is the floor actually reachable, not a chosen offset. See the WHY NOT
  // EXPOSURE ALONE note above kLinesOnlyScenes[] for why -8 alone is not enough and the white
  // canvas below is what does the work.
  float exposure_offset;
  // The coordinate grid's colour, sRGB (GuiState::grid_color, exported as GridLineParam::color_).
  // White `{1,1,1}` for the simulation scenes — GuiState::grid_color's own default
  // (src/gui/gui_state.hpp:1374), so this field is byte-unchanged for those four rows, not merely
  // asserted to be; black for the lines-only scenes, whose canvas is white — see the note above
  // kLinesOnlyScenes[].
  float grid_srgb[3];
  // Ray budget, in millions. Must be a dyadic fraction so ExpectedSimRayNum's truncation and
  // rounding agree — see its note in test_gui_shared.hpp.
  float ray_num_millions;
  // The floor for the 4x4 BLOCK-MEAN PSNR of the two images (support/block_mean_psnr.hpp), not
  // for the whole-frame PSNR, which is still computed and printed beside it as a diagnostic. See
  // the BLOCK MEAN note above kScenes[] for why the ruler changed and what the rows read under
  // each.
  double bm4_threshold;
  // What the export arm must compute for the canvas, asserted before the images are compared so a
  // size disagreement is reported as itself rather than as a PSNR failure.
  int expect_w;
  int expect_h;
};

// Both scenes share one document (test/e2e/configs/halo_22.json: prism crystals, sun at 20
// degrees) and differ only in how it is framed, so a PSNR drop localizes to the framing rather
// than to the scene.
//
// EXPOSURE. Both scenes pin relative EV, overriding the absolute the document asks for, and that
// is a statement about what absolute mode promises rather than a convenience. Absolute mode
// anchors on emitted energy and normalizes by the frame's own pixel COUNT
// (src/server/render.cpp ExposureScale, src/gui/mono_exposure_scale.hpp), so the brightness it
// produces is a function of the canvas and the lens. The GUI preview's pixels come from the
// full-sky simulation texture and are scaled by THAT texture's pixel count; the CLI renders the
// scene's own lens directly into the exported canvas and scales by its. The two therefore differ
// by a fixed factor whenever the exported canvas is not the simulation texture's own shape —
// which is the "comparable only at equal lens / FOV / resolution" boundary
// doc/ev-pipeline-architecture.md states for absolute mode, not a defect for this fixture to
// report. Relative mode has no such term: both sides read ONE anchor.
//
// Relative mode used to leave a residual behind, and this note used to state it: the two anchors
// were P99 over DIFFERENT pixel populations (the GUI's over the whole simulation texture, the
// CLI's over the framed view), so a narrow frame read brighter on the GUI side — measured on the
