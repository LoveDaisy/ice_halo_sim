// CLI<->GUI export parity — the gate that makes "what the GUI shows is what the exported config
// renders" a proposition something can turn red on.
//
// The proposition. A document is loaded in the GUI, a scene's view settings are applied, the run
// completes, and two images are produced from that one document:
//   (1) the GUI side, through the SAME per-frame PreviewParams assembly the product uses
//       (src/gui/app_panels.cpp fills g_preview_vp.params from GuiState every frame), rendered
//       off-screen by gui::ExportPreviewPng;
//   (2) the CLI side, by handing gui::BuildExportJsonOrWarn's output to the Lumice CLI binary in
//       a child process and reading the image it writes.
// The two are compared — by a 4x4 block-mean PSNR for the simulation scenes and by a membership
// mask for the lines-only scenes; each ruler is argued where its scenes are declared. Nothing here
// re-encodes a field by hand: both sides come out of production functions, which is the point — a
// fixture that rebuilt the export JSON itself would be a second mirror of the very code under test.
//
// Why a category of its own, in a directory of its own. Everything under test/gui/visual/ compares
// a capture against a COMMITTED reference image and is therefore regenerated by
// scripts/regen_gui_test_refs.py's GROUPS registry. This suite compares two renders made in the
// same run; it owns no committed asset and must never be added to that registry. The directory
// boundary says so structurally, so a contributor does not have to read this comment to find out.
//
// What it does NOT subsume. Three sibling comparisons stay where they are, because each answers a
// different proposition:
//   * test/e2e-correctness/test_ev_mode_relative_gui_parity.py compares the CLI's baked image
//     against the GUI's exposure FORMULA re-run over the same buffer through the C API. No GUI
//     process, no shader; its own docstring records that it strips the scene down to exposure
//     alone precisely because background / ray_color / grid / outline are baked by the CLI and
//     not by LUMICE_XyzToSrgbUint8.
//   * test/unit-correctness/gui/test_visible_mask_gui_parity.cpp and
//     test/unit-correctness/gui/test_horizon_gui_parity.cpp compare core's C++ predicate against a
//     CPU mirror of the GLSL one. They answer the SHAPE of the disagreement (which pixels, and on
//     which side of which boundary) — something a whole-image PSNR cannot express — and they need
//     no display, so they run on every platform. Complementary, not duplicated.
//
// ============================ Field coverage and measured sensitivity ========================
//
// The fields src/gui/file_io.cpp's BuildScene fills only on its kJsonExport arm, and what each
// scene does with them. The right-hand columns are MEASURED, not asserted: each is the PSNR the
// scene lands at when that one field is broken single-sided in the export arm (and only there).
// The annotation rows (horizon / angular_dist / elevation / longitude) and the overlap row were
// re-measured at v4.28's operating point against thresholds of 27.2 / 31.0 dB; the view and
// background rows are carried from the calibration before it, against 25.5 / 26.0 dB — those
// fields did not move, and their breaks are an order of magnitude below any threshold this file
// has held. They are what says this gate can actually see the field.
//
// Two of the three scenes appear here. The third, `single_lens_rectilinear`, is not a field-
// coverage column: it holds the same view fields as `single_lens_angled` on purpose, and what it
// adds is the PROJECTION FAMILY axis described further down — it is the scene that can see the
// preview shader's relative-illumination factor, which neither equal-area column can.
//
//   field          | single_lens_angled       | broken | full_sky_dual_fisheye     | broken
//   ---------------|-------------------------|--------|---------------------------|--------
//   lens_type      | fisheye_equal_area      |  13.31 | dual_fisheye_equal_area   |   n/a
//   lens_fov       | 96 (non-default)        |  21.32 | 180                       |   n/a
//   visible        | upper                   |  16.85 | full                      |   n/a
//   view_azimuth   | 25, applied             |  19.56 | forced to 0 (full-sky)    |   n/a
//   view_elevation | 30, applied             |  15.31 | forced to 0 (full-sky)    |   n/a
//   view_roll      | 15, applied             |  19.53 | forced to 0 (full-sky)    |   n/a
//   background     | (0.10, 0.16, 0.28)      |  17.21 | (0.28, 0.14, 0.10)        |  18.16
//   resolution     | 4:3 + portrait -> 512x683 | canvas assert | no ratio -> 1024x512 |  n/a
//   horizon        | on                      |  27.23 | on                        |  29.72
//   angular_dist   | on, {22, 46} deg        |  26.42 | on, {22, 46} deg          |  29.76
//   elevation      | on, 10 deg step         |  24.98 | on, 30 deg step           |    n/a
//   longitude      | on, 10 deg step         |  26.93 | on, 30 deg step           |  25.47
//   markers        | all six, zenith imaged  |    n/a | all six, all imaged       |    n/a
//   overlap        | n/a (single lens)       |    n/a | 0 (the screen's disc)     | 15.0 at 0.0872
//
//   tone           | screen (the default)    |    n/a | screen (the default)      |   n/a
//   paper          | unused under screen     |    n/a | unused under screen       |   n/a
//
// The last two rows are "n/a" in both columns because both of these scenes are SCREEN-toned, which is
// the pre-print behaviour and the value a zero-initialized export carries. Those two fields are
// covered by a FOURTH scene, `full_sky_dual_fisheye_print`, which is the only row here that is not a
// variation of framing: it varies the operator. Its own entry below carries the calibration, the two
// measured breaks, and — stated there rather than left to be discovered — the one break it cannot
// see and where that one is gated instead.
//
// The markers row's two "n/a"s are MEASURED, and they are a statement about the metric rather
// than about the field. A ring of the default 8 px radius covers roughly 150 pixels; deleting the
// CLI's nadir ring outright moved the full-sky scene by 0.02 dB, and UPWARD — the ring's presence
// costs a little parity (see below), so removing it reads as an improvement. A whole-frame PSNR
// cannot see this field, and the honest response is to say so rather than to pick a threshold that
// pretends otherwise. Growing the family from two rings to six did not change that: it moved both
// scenes DOWN by about 0.4 dB (the per-ring edge cost, four more times over), which is a shift of
// the baseline rather than a sensitivity the metric acquired.
//
// Enlarging the rings until it could see them was tried and rejected on the measurement: at radius
// 60 / 30 the full-sky scene falls from 27.62 to 27.09 dB, which is BELOW its threshold and within
// 0.2 dB of the smallest break it is supposed to catch. What that radius makes visible is not the
// marker's position but the two arms' edge models — the preview shader antialiases the ring with
// smoothstep over 1.5 px (overlayAuxLines), the CLI applies a hard 1.5 px distance test
// (server/render.cpp PostSnapshot) — so the enlarged ring would spend this gate's whole margin
// re-measuring a divergence it did not introduce, and would weaken every other row in the table by
// forcing the threshold down. Same reasoning as the GRID OPACITY note above, reaching the opposite
// action because a ring's edge is a fixed fraction of a ring rather than a removable alpha term.
//
// So what the markers are covered BY here is the export encoding, not the pixels: the fixture
// asserts that the exported document lists all six grid.markers entries and that their `enabled`
// follows the scene's switch (ParseExportedRenderInfo), which is the half of the path that lives in
// BuildScene's export arm and the half that a regression would silently drop. Where the rings LAND
// is pinned by test/unit-correctness/gui/test_annotation_overlay_gui_parity.cpp (against the GUI's
// own former projection, at a resolution this metric does not have) and, for the four sun-relative
// members that projection never covered, by test/gui/functional/test_marker_panel.cpp, which reads
// each ring's colour off a rendered frame.
//
// Why all six here rather than a representative pair: the four sun-relative directions are the only
// annotation in this table whose position depends on a document field OTHER than the view. Exporting
// them exercises the one thing the two-marker version could not — that the child process places them
// where the preview did, from the sun the document names.
//
// The angular_dist row is broken two ways rather than one, because the two shapes it can fail in
// are independent and the weaker one sets the threshold. Shifting every circle by ONE degree in
// the CLI arm costs 23.68 / 25.38 dB; making the CLI draw only the FIRST of the two lines costs
// 25.73 / 26.89 dB, and that second, weaker break is the one the columns above report.
//
// The two grid rows are broken by dropping ONE line from the CLI arm — the smallest break the
// family has, since dropping the whole family is what a missing branch would do and costs far
// more. They are the reason the grid is worth two rows rather than one: a parallel and a meridian
// are different curves in the export arm (different Request field, different Overlay mask), and
// each column sees one of them clearly. The "n/a" on elevation / full_sky is measured, not
// assumed: at a 30 deg step the outermost parallel is the 80 deg one, which on a dual-fisheye
// frame is a small circle near each disc centre — dropping it moved that scene by 0.01 dB. Its
// meridians span a whole disc and cost 3.5 dB, which is where that scene's grid sensitivity lives.
// Symmetrically, single_lens_angled sees a dropped parallel at 2.3 dB and a dropped meridian at
// 0.47 dB, the latter under its threshold. So each grid break is caught by at least one column,
// which is the same structure the view-angle rows above already have.
//
// GRID OPACITY IS 1.0 IN BOTH SCENES, not the 0.3 a user gets, and this is the one appearance
// value either scene overrides. The reason is a divergence this gate is not the place to measure:
// the CLI blends an overlay line into radiance BEFORE the sRGB transfer curve (server/render.cpp
// PostSnapshot) while the preview shader blends it AFTER (overlayAuxLines runs on the already
// gamma-encoded colour), so a partially transparent line lands on different bytes even where it
// covers exactly the same pixels. Measured on full_sky_dual_fisheye at alpha 0.3 over its
// background: 129 vs 160 per channel on a line pixel, which matches the two formulas to within a
// count and costs 2.9 dB of whole-frame PSNR. At alpha 1 the background term drops out of both and
// they agree exactly. The divergence is older than the grid — it applies to the circles and the
// horizon too — and belongs to whoever unifies the two compositors; pinning it here would only
// bury this gate's actual subject, which is WHERE the curves land.
//
// "n/a" means the break does not move that scene, and in every case for a stated reason rather
// than a gap: the full-sky lens family ignores fov and zeroes the three view angles, so a break in
// those cannot show there; `visible` and `lens_type` are broken TO the value that scene already
// holds; and the markers cells are discussed above. Each field is therefore live in at least one
// column, and the two columns between them cover both sides of every branch the export arm has —
// single lens vs the full-sky family, an aspect preset that names a ratio vs the two that name
// none and fall back to 2:1 — rather than nine unrelated checkmarks.
//
// The `resolution` break is the one that does not report as a PSNR drop: the canvas assertion in
// TestFunc fires first, because a wrong canvas is a finding in its own right and is worth saying
// as itself. That is deliberate; do not "fix" it into a PSNR comparison by resizing.
//
// ================================= Deliberately not covered ==================================
//
//   * The lens border, which remains a GUI display-time layer with no encoding in the config
//     format, so there is still nothing on the CLI side to compare against. Off in both scenes,
//     which is also its default.
//   * The TEXT LABELS, and this one is now an exclusion with a reason rather than a gap. As of
//     v4.21 they ARE encoded (grid.horizon_label / grid.label / grid.angular_dist_label) and the
//     CLI does draw them, from the same core anchors the GUI reads — so the placement half of
//     "what the GUI shows is what the export renders" is already covered by the curves those
//     anchors sit on. What is NOT comparable is the GLYPHS: the GUI rasterizes through ImGui's
//     font atlas and its draw list, core through stb_truetype into the image buffer, and the two
//     also differ in what they do around a label — the GUI clamps a label inside the viewport and
//     drops one that collides with another, the CLI draws every anchor where core put it. Both
//     halves are deliberate (see src/core/annotation_font.hpp and the CLI-side notes in
//     server/render.cpp), so a pixel comparison here would pin two rasterizers against each other,
//     which is not this gate's subject. All three switches are off in both scenes, which is also
//     their default.
//
//     The sun circles USED to be on this list, with the note "re-add coverage here the day core
//     gains an annotation layer". That day came, and the altitude grid followed it: both are now on
//     in both scenes. The two arms are two EVALUATORS of one definition rather than two
//     implementations of a curve: each family is a level set of a world-space angle field with the
//     line-width rule src/util/annotation_line_width.hpp owns, and the CLI evaluates it on the CPU
//     (server/render.cpp through core's LevelSetMaskFromField, once per line) while the preview
//     evaluates it per fragment in its shader (preview_renderer.cpp overlayAuxLines, from the same
//     forward differences, as the hard set with no antialiasing — see the ANNOTATION EVALUATION
//     note below for the three ways of doing it differently that this fixture measured and
//     rejected). The curves land on the same pixels to within a handful per frame, so turning a
//     family ON raises both scenes' PSNR rather than lowering it, and a drop is the signal the
//     thresholds below are set against.
//
//     ANNOTATION EVALUATION, measured when the curves went back to the shader (v4.28). Three
//     shapes of "the same definition, evaluated differently" were tried, and this fixture is what
//     rejected each: an antialiased smoothstep line (half the CLI's ink: 18.2 / 14.8 / 19.9 dB
//     against thresholds of 27 / 27.1 / 34), a pixel-coverage ramp of the CLI's set (positions
//     within half a pixel, but a one-pixel fringe on every edge against a hard band: 24.2 / 15.0 /
//     27.4), and the hardware fwidth() in place of the CPU's forward differences (a quad-based
//     derivative that disagrees with the CPU on ~200 pixels a frame: -1.8 dB on the rectilinear
//     scene). What survived is the CPU's own rule, evaluated per fragment. The fourth number in
//     each triple above, 15 dB on full_sky_dual_fisheye, was not the line at all: it was the
//     export arm carrying a dual-fisheye `overlap` the screen never shows, which put the CLI's
//     whole disc 4 % outside the GUI's — see the RE-MEASURED note on that scene's row.
//
//     The zenith/nadir markers left the list the same way and are on in both scenes, but they are
//     the member that does NOT raise the figure: measured at the default radius, switching the two
//     legacy rings on cost the full-sky scene 0.08 dB and left the single-lens scene where it was,
//     and growing the family to six cost about 0.4 dB more on both. Both arms put every ring in the
//     same place — that is core's one answer, read twice — and what the cost buys is the difference
//     between an antialiased ring edge and a hard one, once per ring. It is a fixed, understood
//     cost carried on purpose so the export path runs end to end here; see the markers row in the
//     field table for why the alternative (a ring big enough for the metric to see) was measured
//     and rejected.
//   * The colour space an overlay line is composited in, which the two arms genuinely disagree
//     about. Measured, excluded on purpose, and neutralised rather than tolerated — see the
//     GRID OPACITY note above the field table for the numbers and the mechanism.
//     A HORIZON exclusion used to stand here, and it is gone rather than relaxed. Both scenes kept
//     the switch OFF because the two renderers did not draw the same line: enabling it on both
//     sides cost the full-sky scene 1.61 dB, of which turning the CLI's line back off recovered
//     1.43 dB — nearly all of the mismatch was core's line landing where the GUI's was not. The
//     GUI's was a shader line whose width came from fwidth() of the altitude field, core's a mask
//     built at a fixed pixel width, and on a dual-fisheye frame those two widths parted company
//     near the circle rim. The shader reads core's mask now, so the horizon joined the "two
//     readings of one curve" family and both scenes have it ON: enabling it GAINS 0.10 dB on the
//     full-sky scene and 0.04 on the single-lens one, measured against the same session's OFF run.
//     What survives is a residual the field table's GRID OPACITY note explains, not an exclusion:
//     the horizon composites at alpha 0.6 on both arms and cannot be raised to 1 the way the grid
//     and the markers are, because core paints it from a fixed constant with no config field. The
//     direction the OFF state used to pin — the export must not assert a line the user switched
//     off, which it once wrote the INVERSE of — does not move here with it, and does not need to:
//     it is a question about a JSON field, and test_scene_commit_chain.cpp asks it as one
//     (TheExportIntentDescribesTheDocumentsView, with the switch off). What this file adds on top is
//     the ON half of the same claim, read out of the document the child process actually reads —
//     see info.horizon below, which mirrors info.markers_listed / info.markers_enabled.
//   * The single-lens fisheye domain past theta = 90 degrees. This USED to be a real and large
//     exclusion — the preview shader kept inverting toward the frame corners while core stopped at
//     the equator, and a 4:3 frame at fov 150 measured 25% of its pixels lit by the GUI and black
//     in the CLI. That gap was closed in 474.1 (core's cull is now per lens type and runs to
//     theta = 180 deg for equal-area and equidistant), and the pixel-for-pixel comparison of the
//     two domains lives where it can be made cheaply and exhaustively: the unit-level mask gate
//     test/unit-correctness/gui/test_visible_mask_gui_parity.cpp. It stays off this fixture's list
//     not because it diverges but because this fixture compares RENDERED energy on a scene whose
//     fov keeps the whole frame well inside both domains; widening its fov to exercise the rim
//     would buy a duplicate of that unit gate at the cost of a much noisier oracle.
//   * A loaded background IMAGE (GuiState::bg_*). Owner-decided GUI-only: it is never exported, so
//     there is no honest comparison to make. Neither scene loads one.
//   * RenderConfig::ray_color. The GUI's tint control does not reach the renderer, and the export
//     writes core's "use the natural spectral colour" sentinel; there is no divergence to detect.
//   * RenderConfig::front (the front-hemisphere clip). It IS exported now — core gained the field
//     and the old refusal is gone — so this is a genuine gap rather than a structural one, and it
//     is left open deliberately. What the clip needs proved is that core's mask and the shader cut
//     the same pixels, and that is already pinned exactly, per pixel, by
//     test_visible_mask_gui_parity.cpp's FrontClipMatchesTheGuiRule, which compares the two
//     implementations directly instead of comparing two rendered images of them. A scene here would
//     re-ask the same question through a noisier instrument (a child CLI process and a PSNR floor).
//     Add one if the clip ever acquires behaviour beyond the mask — a ray-level cull, say.
//   * lens_shift. The GUI exposes no control for it, so there is no user-visible value the export
//     could be dishonest about.
//   * The exposure anchor. See the note above kScenes[]: both scenes pin relative EV, and what is
//     left over after that is a measured, stated residual rather than an evasion.
//   * A lines-only (member-mask) variant of full_sky_dual_fisheye_print. Measured before deciding,
//     not assumed: the subtractive print operator (doc/print-mode-subtractive-ink.md) has no
//     saturation floor the way the additive screen operator does — paper * 10^(-D) can only go
//     DOWN from the paper colour, so the simulated arcs' residue always lands on the page rather
//     than being clamped away. At the same exposure floor the screen scenes use (2^-8), the two
//     "not paper" masks XOR to 45347 px (largest blob 2708) at tau = 0, still 19 px (largest blob
//     3) at tau = 2 — the same "use tau to hide it" tolerance this file's screen scenes refuse.
//     See the NO PRINT SCENE note above kLinesOnlyScenes[] for the full numbers.
//
// ====================================== Platform reach =======================================
//
// Do not read a green CI as a green here. gui_test is COMPILED on macOS, Windows and Linux but RUN
// by exactly one CI leg (.github/workflows/ci.yml, Ubuntu x86_64 under xvfb-run with Mesa
// llvmpipe), and that leg passes a hand-picked positive filter naming only two reference groups.
// This category is not in it, in company with most of this binary's categories, so today NO CI job
// executes this fixture. The two pytest legs build with -DBUILD_GUI=OFF and do not have the binary
// at all. Where it does run is a developer machine with a working GL context: scripts/build.sh's
// correctness pool selects tests by a NEGATIVE filter, so this category is included by default,
// and ./scripts/test.sh {quick,full,pr} therefore executes it. doc/testing-architecture.md 7.5 has
// the mechanism, the measured cost of putting this tag in CI, and why the llvmpipe leg is not
// currently the right home for it. This is a RECORDED STATE, not a defect awaiting a fix.
//
// This is also the first place in the repo where a test binary starts the CLI binary as a child
// process. See RunCliRender below for the mechanics and for what that costs in portability.

